# Pseudo-unit markers of the linked program, authored from the linked symbols.
LINK_MARKERS = {
    "caml_startup.code_begin": "startup stub, code-section start",
    "caml_startup.code_end": "startup stub, code-section end",
    "caml_startup.data_begin": "startup stub, data-section start",
    "caml_startup.data_end": "startup stub, data-section end",
    "caml_startup.frametable": "startup stub, frame table",
    "caml_startup.gc_roots": "startup stub, GC root table",
    "caml_hot.code_begin": "runtime hot-section start",
    "caml_hot.code_end": "runtime hot-section end",
    "caml_system.frametable": "runtime system pseudo-unit, frame table",
    "caml_system__code_begin": "runtime system object, code-section start",
    "caml_system__code_end": "runtime system object, code-section end",
}

# Linked-program symbols the contract refuses, keyed by the symbol. They are
# hand-authored because the extractor only lists the names the toolchain emits:
# each one is a suffix form the contract deliberately does not claim.
LINK_UNSUPPORTED = {
    "camlOcaml_probe.f_1.cold": "host fragment suffix on an OCaml-generated member",
    "caml_ba_compare.cold.1": "LLVM cold-fragment index, not measured on the runtime",
    "caml_ba_compare.part.": "partial-inlining fragment without an index",
    "caml_other__code_begin": "pseudo-unit the runtime does not have",
    "camlOcaml_probe.3.1": "nested static-data label",
}


def is_alpha(byte: int) -> bool:
    return 0x30 <= byte <= 0x39 or 0x41 <= byte <= 0x5A or 0x61 <= byte <= 0x7A


def is_upper(byte: int) -> bool:
    return 0x41 <= byte <= 0x5A


def is_lower_hex(byte: int) -> bool:
    return 0x30 <= byte <= 0x39 or 0x61 <= byte <= 0x66


def escape_at(symbol: bytes, index: int) -> int | None:
    """The index after the `$XX` escape at `index`, if there is one."""
    if index + 2 >= len(symbol) or symbol[index] != 0x24:
        return None
    if not is_lower_hex(symbol[index + 1]) or not is_lower_hex(symbol[index + 2]):
        return None
    return index + 3


def parse_segment(symbol: bytes, index: int) -> int | None:
    if index >= len(symbol) or not is_upper(symbol[index]):
        return None
    index += 1
    while index < len(symbol):
        byte = symbol[index]
        if is_alpha(byte) or byte == 0x5F:
            index += 1
        elif byte == 0x24:
            index = escape_at(symbol, index)
            if index is None:
                return None
        else:
            break
    return index


def stamped_body(member: bytes) -> bytes | None:
    index = member.rfind(b"_")
    if index <= 0:
        return None
    body, stamp = member[:index], member[index + 1 :]
    if not stamp or not all(0x30 <= byte <= 0x39 for byte in stamp):
        return None
    return body


def parse_member(symbol: bytes, index: int) -> bytes | None:
    start = index
    while index < len(symbol):
        byte = symbol[index]
        if is_alpha(byte) or byte == 0x5F:
            index += 1
        elif byte == 0x24:
            index = escape_at(symbol, index)
            if index is None:
                return None
        elif byte == 0x2E and index == start and symbol[index + 1 : index + 2] == b"$":
            index += 1
        else:
            break
    if index != len(symbol) or index == start:
        return None
    member = symbol[start:index]
    if member.decode("ascii") in MARKERS:
        return member
    return stamped_body(member)


def decode(bytes_: bytes) -> str:
    out = bytearray()
    index = 0
    while index < len(bytes_):
        after = escape_at(bytes_, index)
        if after is not None:
            value = int(bytes_[index + 1 : index + 3], 16)
            if 0x21 <= value <= 0x7E and value != 0x2E:
                out.append(value)
            else:
                out += bytes_[index:after]
            index = after
            continue
        out.append(bytes_[index])
        index += 1
    return out.decode("ascii")


def fragment_base(body: bytes) -> bytes | None:
    """The helper name a host-compiler fragment suffix belongs to."""
    if body.endswith(b".cold"):
        return body[: -len(b".cold")]
    index = body.rfind(b".part.")
    if index <= 0:
        return None
    digits = body[index + len(b".part.") :]
    if not digits or not all(0x30 <= byte <= 0x39 for byte in digits):
        return None
    return body[:index]


def contract(symbol: str) -> tuple[str, str] | None:
    """Return the (kind, printed text) the display contract gives a symbol."""
    bytes_ = symbol.encode()
    index = bytes_.find(b".llvm.")
    if index > 0 and all(byte in b"0123456789ABCDEF" for byte in bytes_[index + 6 :]):
        bytes_ = bytes_[:index]
    if bytes_.startswith(b"_") and not bytes_.startswith(b"caml"):
        bytes_ = bytes_[1:]
    if not bytes_.startswith(b"caml"):
        return None
    body = bytes_[4:]

    if body.startswith(b"_"):
        index = 1
        name_start = index
        while True:
            word_start = index
            while index < len(body) and is_alpha(body[index]):
                index += 1
            if index == word_start:
                return None
            if index < len(body) and body[index] == 0x5F:
                # A doubled underscore starts the assembler's
                # `caml_<unit>__<marker>` spelling, not another name word.
                if body[index + 1 : index + 2] == b"_":
                    break
                index += 1
                continue
            break
        name = body[name_start:index]
        if index == len(body):
            return ("helper", bytes_.decode())
        base = fragment_base(body)
        if base is not None:
            inner = contract("caml" + base.decode())
            if inner is not None and inner[0] == "helper":
                return ("fragment", inner[1])
            return None
        if decode(name) not in PSEUDO_UNITS:
            return None
        if body[index : index + 2] == b"__":
            marker = body[index + 2 :].decode()
            if marker not in MARKERS:
                return None
            return ("marker", f"{decode(name)}__{marker}")
        if body[index] != 0x2E:
            return None
        marker = body[index + 1 :].decode()
        if marker not in MARKERS:
            return None
        return ("unit", f"{decode(name)}.{marker}")

    start = 0
    index = parse_segment(body, 0)
    if index is None:
        return None
    segments = 1
    while True:
        if index == len(body):
            return ("module", decode(body[start:index]))
        if body[index] != 0x2E:
            return None
        member = parse_member(body, index + 1)
        if member is not None:
            return ("member", f"{decode(body[start:index])}.{decode(member)}")
        label = body[index + 1 :]
        if label and all(0x30 <= byte <= 0x39 for byte in label):
            return ("label", f"{decode(body[start:index])}.{label.decode()}")
        if segments >= 64 or index + 1 >= len(body) or not is_upper(body[index + 1]):
            return None
        index = parse_segment(body, index + 1)
        if index is None:
            return None
        segments += 1


def fixture_rows(symbols: list[str]) -> list[tuple[str, str, str, str, str]]:
    """Rows for the fixture and pack symbols, with source-authored notes."""
    expected: dict[str, str] = {}
    for path, values in MODULES.items():
        expected[path] = "compilation-unit module record"
        for marker, note in MARKERS.items():
            expected[f"{path}.{marker}"] = note
        for value, note in values.items():
            expected[f"{path}.{value}"] = note

    rows = []
    for symbol in symbols:
        parsed = contract(symbol)
        if parsed is None:
            raise SystemExit(f"fixture symbol {symbol} is not a contract form")
        kind, text = parsed
        if kind == "label":
            unit = text.split(".")[0]
            note = LABEL_NOTE.format(unit=unit)
        else:
            note = expected.get(text)
            if note is None:
                raise SystemExit(
                    f"fixture symbol {symbol} -> {text!r} has no source note"
                )
        rows.append((symbol, "fixture", "exact", text, note))
    return rows


def reject_note(symbol: str) -> str:
    member = symbol.rsplit(".", 1)[-1]
    if member.isdigit():
        return "numeric static-data label"
    if symbol.endswith(".cold"):
        return "C section suffix on a runtime function"
    if "__" in symbol:
        return "runtime double-underscore marker"
    return "unrecognised `caml` form"


def link_rows(symbols: list[str]) -> list[tuple[str, str, str, str, str]]:
    """Rows for the runtime helpers, pseudo-unit markers and rejects.

    Module and value rows of the linked program are skipped: they repeat what
    the fixture and the standard library archive already cover.
    """
    rows = []
    for symbol in symbols:
        parsed = contract(symbol)
        if parsed is None:
            rows.append((symbol, "link", "unsupported", "", reject_note(symbol)))
            continue
        kind, text = parsed
        if kind == "helper":
            rows.append((symbol, "runtime", "identity", symbol, "runtime helper"))
        elif kind in ("unit", "marker"):
            note = LINK_MARKERS.get(symbol)
            if note is None:
                raise SystemExit(f"linked symbol {symbol} has no authored note")
            rows.append((symbol, "link", "exact", text, note))
    for symbol, note in LINK_UNSUPPORTED.items():
        rows.append((symbol, "link", "unsupported", "", note))
    return rows


def fragment_rows(symbols: list[str]) -> list[tuple[str, str, str, str, str]]:
    """Rows for the host-compiler fragments of runtime helpers."""
    rows = []
    for symbol in symbols:
        parsed = contract(symbol)
        if parsed is None or parsed[0] != "fragment":
            raise SystemExit(f"linked fragment {symbol} is not a contract form")
        base = parsed[1]
        if symbol.endswith(".cold"):
            note = "GCC cold-half fragment; the suffix is not part of the name"
        else:
            note = "partial-inlining fragment; the suffix is not part of the name"
        rows.append((symbol, "fragment", "exact", base, f"{base}: {note}"))
    return rows


def stdlib_rows(symbols: list[str]) -> list[tuple[str, str, str, str, str]]:
    """Rows for the installed standard library archive, contract-derived."""
    rows = []
    for symbol in symbols:
        parsed = contract(symbol)
        if parsed is None:
            rows.append((symbol, "stdlib", "unsupported", "", reject_note(symbol)))
            continue
        kind, text = parsed
        unit = text.split(".")[0]
        note = {
            "module": "module record of a standard library unit",
            "member": "member of a standard library unit",
        }.get(kind, "standard library symbol")
        if kind == "member":
            member = text.rsplit(".", 1)[1]
            if "$" in member or any(not (char.isalnum() or char in "_'") for char in member):
                note = "escaped or operator member of a standard library unit"
            elif member in MARKERS:
                note = f"{MARKERS[member]} of a standard library unit"
        rows.append((symbol, "stdlib", "contract", text, f"{unit}: {note}"))
    return rows


