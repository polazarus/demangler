def sections() -> dict[str, list[str]]:
    output = subprocess.run(
        [os.path.join(HERE, "extract-symbols.sh")],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    result: dict[str, list[str]] = {}
    current = None
    for line in output.splitlines():
        if line.startswith("#"):
            current = line[1:]
            result[current] = []
        elif line and current is not None:
            result[current].append(line)
    return result


def main() -> int:
    data = sections()
    fixture = fixture_rows(data["fixture"] + data["pack"])
    stdlib = stdlib_rows(data["stdlib"])
    covered = {row[0] for row in fixture} | {row[0] for row in stdlib}
    link = [row for row in link_rows(data["link"]) if row[0] not in covered]
    tables = {
        "fixture.tsv": fixture,
        "runtime.tsv": [row for row in link if row[1] == "runtime"],
        "link.tsv": [row for row in link if row[1] == "link"],
        "fragments.tsv": fragment_rows(data["fragments"]),
        "stdlib.tsv": stdlib,
    }

    check = "--check" in sys.argv[1:]
    failures = []
    os.makedirs(CORPUS, exist_ok=True)
    for name, rows in tables.items():
        body = "\n".join("\t".join(row) for row in rows) + "\n"
        text = "".join(f"# {line}\n" for line in HEADERS[name]) + body
        path = os.path.join(CORPUS, name)
        if check:
            existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if existing != text:
                failures.append(f"{name}: stale")
            continue
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"{name}: {len(rows)} rows")

    if failures:
        raise SystemExit(", ".join(failures))
    return 0


if __name__ == "__main__":
    sys.exit(main())
